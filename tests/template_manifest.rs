//! End-to-end coverage for `kind = "template"`: a version sink generated from a Jinja template
//! (issue #65, specs S1-S7 in `odd/tasks/manifest-template-kind.md`).

mod common;

use common::*;
use cutver::bump::run as bump_run;
use cutver::config;
use cutver::semver_bump::Bump;

/// A configuration whose version source is `Cargo.toml` and whose sink is `src/version.ts`,
/// generated from the template beside it. Mirrors the shape the issue proposes.
fn write_fixture(fixture: &Fixture) {
    fixture.write(
        "cutver.toml",
        r#"[version]
current_source = "Cargo.toml"

[[manifest]]
path = "Cargo.toml"
kind = "cargo-package"

[[manifest]]
path = "src/version.ts"
kind = "template"
template = "src/version.ts.jinja"

[preflight]

[changelog]
path = "CHANGELOG.md"
"#,
    );
    fixture.write(
        "Cargo.toml",
        "[package]\nname = \"demo\"\nversion = \"1.0.0\"\nedition = \"2021\"\n",
    );
    fixture.write(
        "src/version.ts.jinja",
        "// generated by cutver\nexport const VERSION = \"{{ version }}\";\nexport const TAG = \"{{ tag }}\";\n",
    );
    fixture.write("CHANGELOG.md", "# Changelog\n");
}

fn commit(fixture: &Fixture, message: &str) {
    fixture.write("src/touch.txt", message);
    run_git_ok(&fixture.dir, &["add", "."]);
    run_git_ok(&fixture.dir, &["commit", "-m", message]);
}

/// S2 + S7: the sink is generated from the release context, byte-exact, and the version source is
/// still the in-place manifest.
#[test]
fn bump_generates_a_template_sink_from_the_release_context() {
    let guard = FixtureGuard::new("sink-context");
    let fixture = guard.fixture();
    write_fixture(fixture);
    init_git_repo(fixture);
    initial_commit(fixture);
    run_git_ok(&fixture.dir, &["tag", "v1.0.0"]);
    commit(fixture, "feat: add a sink");

    let cfg = config::load("cutver.toml").unwrap();
    bump_run(&cfg, Bump::Minor, false, &[]).expect("bump should succeed with a template sink");

    assert_eq!(
        fixture.read("src/version.ts"),
        "// generated by cutver\nexport const VERSION = \"1.1.0\";\nexport const TAG = \"v1.1.0\";\n",
        "the sink must render the release context byte-exact, trailing newline included"
    );
    // S8: the in-place editor still bumped its own file.
    assert!(
        fixture.read("Cargo.toml").contains("version = \"1.1.0\""),
        "the version source must still be bumped in place"
    );
}

/// S1: without an explicit `template`, the sink reads `<path>.jinja`.
#[test]
fn a_sink_defaults_to_the_template_beside_its_target() {
    let guard = FixtureGuard::new("sink-default");
    let fixture = guard.fixture();
    fixture.write(
        "cutver.toml",
        r#"[version]
current_source = "Cargo.toml"

[[manifest]]
path = "Cargo.toml"
kind = "cargo-package"

[[manifest]]
path = "include/version.h"
kind = "template"

[preflight]
"#,
    );
    fixture.write(
        "Cargo.toml",
        "[package]\nname = \"demo\"\nversion = \"2.0.0\"\nedition = \"2021\"\n",
    );
    fixture.write("include/version.h.jinja", "#define DEMO_VERSION \"{{ version }}\"\n");
    init_git_repo(fixture);
    initial_commit(fixture);
    commit(fixture, "feat: default template path");

    let cfg = config::load("cutver.toml").unwrap();
    bump_run(&cfg, Bump::Minor, false, &[]).expect("bump should succeed with the default template");

    assert_eq!(fixture.read("include/version.h"), "#define DEMO_VERSION \"2.1.0\"\n");
}

/// S6: a missing template is an actionable error naming the path, not a silent empty render.
#[test]
fn a_missing_template_fails_with_its_path() {
    let guard = FixtureGuard::new("sink-missing");
    let fixture = guard.fixture();
    fixture.write(
        "cutver.toml",
        r#"[version]
current_source = "Cargo.toml"

[[manifest]]
path = "Cargo.toml"
kind = "cargo-package"

[[manifest]]
path = "src/version.ts"
kind = "template"
template = "src/absent.jinja"

[preflight]
"#,
    );
    fixture.write(
        "Cargo.toml",
        "[package]\nname = \"demo\"\nversion = \"1.0.0\"\nedition = \"2021\"\n",
    );
    init_git_repo(fixture);
    initial_commit(fixture);
    commit(fixture, "feat: missing template");

    let cfg = config::load("cutver.toml").unwrap();
    let err = bump_run(&cfg, Bump::Minor, false, &[]).unwrap_err();
    let message = err.to_string();
    assert!(
        message.contains("absent.jinja"),
        "the error must name the missing template: {message}"
    );
}

/// S3: `doctor` detects drift by re-rendering, never by reverse-parsing the generated file.
#[test]
fn doctor_reports_drift_when_the_sink_no_longer_matches_its_template() {
    let guard = FixtureGuard::new("sink-doctor");
    let fixture = guard.fixture();
    write_fixture(fixture);
    init_git_repo(fixture);
    initial_commit(fixture);
    run_git_ok(&fixture.dir, &["tag", "v1.0.0"]);
    commit(fixture, "feat: add a sink");

    let cfg = config::load("cutver.toml").unwrap();
    bump_run(&cfg, Bump::Minor, false, &[]).expect("bump should succeed");
    let generated = fixture.read("src/version.ts");

    // Consistent right after generation: nothing to report.
    let drifts = cutver::bump::doctor(&cfg).expect("doctor should succeed");
    assert!(
        !drifts.iter().any(|d| d.path.ends_with("src/version.ts")),
        "a freshly generated sink must not drift: {drifts:?}"
    );

    // Hand-edit the generated file: the render no longer matches it.
    fixture.write("src/version.ts", &generated.replace("1.1.0", "9.9.9"));
    let drifts = cutver::bump::doctor(&cfg).expect("doctor should succeed");
    assert!(
        drifts.iter().any(|d| d.path.ends_with("src/version.ts")),
        "an edited sink must be reported as drift: {drifts:?}"
    );
}

/// S3: a sink has no version to read, so `doctor` must not fail trying to find one.
#[test]
fn doctor_never_reads_a_version_out_of_a_sink() {
    let guard = FixtureGuard::new("sink-doctor-missing");
    let fixture = guard.fixture();
    write_fixture(fixture);
    init_git_repo(fixture);
    initial_commit(fixture);

    // The sink target does not exist yet: a version-reading check would fail here.
    let cfg = config::load("cutver.toml").unwrap();
    let drifts = cutver::bump::doctor(&cfg).expect("doctor must not fail on an ungenerated sink");
    assert!(
        drifts.iter().any(|d| d.path.ends_with("src/version.ts")),
        "a sink that was never generated is drift: {drifts:?}"
    );
}
